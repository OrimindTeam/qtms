/// تطبيع النصوص — ★ **مصدر الحقيقة الوحيد لكل قيمة يقوم عليها تفرّد أو
/// مطابقة مُطبَّعة** في النظام كله.
///
/// ★ **المرجع المُلزِم:** `IQ-013` — **الخيار أ: تطبيع عربي كامل**
/// (قرار صاحب المشروع 2026-08-24)، ★ **وموثَّق في**
/// `master-data-design.md` §3 **وأثره معلَن في** `data-dictionary.md`.
///
/// ⛔ **ولا نسخة خاصة من هذه القاعدة في `functions/` ولا في الواجهة** —
/// `coding-standards.md` §2.2 («مصدر حقيقة واحد» · `P-10`): نسختان
/// **تفترقان عند أول تعديل**، ⟵ **والافتراق هنا يُنتج كيانين متطابقين في
/// نظر المستخدم مختلفين في نظر النظام**، وهو **فسادُ بيانات صامت لا خطأ
/// يظهر** (`items.normalizedName` مفتاح تفرّد على مستوى النظام).
///
/// ★ **والأثر المقبول معلَن صراحةً في القرار:** التطبيع الكامل **قد يدمج
/// اسمين مختلفين في حالات نادرة** — ⟵ **وهو مقبول لأن الهدف منعُ الازدواج
/// الصامت في البيانات الأساسية لا إثباتُ التطابق اللغوي.**
///
/// ⚠️ **وتطبيع الهاتف ليس هنا بعد** — موضعه هذا الملف نفسه، ⛔ **لكن
/// الصيغة المعيارية لمفتاح الدولة غير محسومة** فلا تُخمَّن: `IQ-014`.
library;

const int _tatweel = 0x0640; // ـ
const int _hamza = 0x0621; // ء
const int _alef = 0x0627; // ا
const int _waw = 0x0648; // و
const int _yeh = 0x064A; // ي
const int _heh = 0x0647; // ه
const int _daggerAlef = 0x0670; // ٰ — ألف خنجرية، وهي تشكيل لا حرف

/// أول التشكيل وآخره — `U+064B` (الفتحتان) حتى `U+065F`، ويشمل
/// **الحوامل المُركَّبة** (`U+0654` الهمزة فوق · `U+0655` الهمزة تحت):
/// فحذفها يُطابق توحيد الهمزات أدناه، ⟵ **فتلتقي الصيغة المُركَّبة
/// والصيغة المُدمَجة على المفتاح نفسه.**
const int _firstDiacritic = 0x064B;
const int _lastDiacritic = 0x065F;

/// توحيد الحروف — ★ **حوامل الهمزة كلها لا ألفاتها وحدها** (`IQ-013`).
const Map<int, int> _foldedLetters = <int, int>{
  0x0623: _alef, // أ
  0x0625: _alef, // إ
  0x0622: _alef, // آ
  0x0671: _alef, // ٱ
  0x0624: _waw, // ؤ
  0x0626: _yeh, // ئ
  0x0629: _heh, // ة ⟵ ه
  0x0649: _yeh, // ى ⟵ ي
};

final RegExp _whitespaceRuns = RegExp(r'\s+');

/// ما يُحذف حذفاً: التطويل · الهمزة المفردة · التشكيل بكل صوره.
bool _isDropped(int rune) =>
    rune == _tatweel ||
    rune == _hamza ||
    rune == _daggerAlef ||
    (rune >= _firstDiacritic && rune <= _lastDiacritic);

/// الصيغة المُطبَّعة لاسم — ★ **وعليها وحدها يجري فحص التفرد**
/// (`glossary.md` · `master-data-design.md` §3).
///
/// تُطبَّق القواعد السبع المعتمدة: حذف التشكيل · حذف التطويل · توحيد حوامل
/// الهمزة · `ة ⟵ ه` · `ى ⟵ ي` · توحيد حالة الأحرف · إزالة المسافات الزائدة.
///
/// ⚠️ **قد تُعيد نصاً فارغاً** لمُدخَل كلُّه تشكيل أو مسافات — ⟵ **والمُدخَل
/// الفارغ يُرفَض عند حدود الإدخال**، ⛔ **ولا يُقبَل مفتاحَ تفرّد.**
String normalizeName(String value) {
  final StringBuffer buffer = StringBuffer();
  for (final int rune in value.runes) {
    if (_isDropped(rune)) continue;
    buffer.writeCharCode(_foldedLetters[rune] ?? rune);
  }
  return buffer
      .toString()
      .toLowerCase()
      .replaceAll(_whitespaceRuns, ' ')
      .trim();
}

