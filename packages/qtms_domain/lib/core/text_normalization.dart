/// أطوال دنيا للحماية من بتر مُدخَل قصير — راجع [_stripYemenPrefix].
const int _minLocalDigits = 7;

/// بادئات مفتاح الدولة اليمني — الأطول أولاً قراءةً لا إلزاماً.
///
/// ⚠️ **ولا يُدَّعى أن الترتيب ملزم:** البادئتان **يستحيل أن تتطابقا معاً**
/// (`00967…` لا يبدأ بـ`967`)، ⟵ **فالترتيب هنا للوضوح لا للصحّة.**
const List<String> _yemenPrefixes = <String>['00967', '967'];

final RegExp _leadingZeros = RegExp(r'^0+');

/// رقم لاتيني مكافئ لأي رقم عربي هندي — أو `null` لغير الأرقام.
///
/// ★ **والتحويل آمن بنيوياً:** التقابل **واحد لواحد**، ⟵ ⛔ **فيستحيل أن
/// يدمج رقمين مختلفين** — وإنما يمنع أن يصير الرقم الواحد مفتاحين لأن
/// لوحة المفاتيح العربية تكتب `٧٧٧` واللاتينية تكتب `777`.
int? _asciiDigitOf(int rune) {
  if (rune >= 0x30 && rune <= 0x39) return rune; // 0-9
  if (rune >= 0x0660 && rune <= 0x0669) return 0x30 + (rune - 0x0660); // ٠-٩
  if (rune >= 0x06F0 && rune <= 0x06F9) return 0x30 + (rune - 0x06F0); // ۰-۹
  return null;
}

/// حذف مفتاح الدولة اليمني إن وُجد — ⛔ **وبحارس طول**.
///
/// ⚠️ **ولماذا الحارس:** بلا شرط الطول يبتر `967` من مُدخَل قصير خاطئ
/// فيُنتج مفتاحاً لرقم لم يكتبه أحد. ★ **ولا رقم يمني محلي يبدأ بـ`967`**:
/// المحمول يبدأ بـ`7` والثابت برمز منطقة `1…7`.
String _stripYemenPrefix(String digits) {
  for (final String prefix in _yemenPrefixes) {
    if (digits.startsWith(prefix) &&
        digits.length - prefix.length >= _minLocalDigits) {
      return digits.substring(prefix.length);
    }
  }
  return digits;
}

/// الصيغة المُطبَّعة لرقم هاتف — ★ **محليّةٌ مجرَّدة بلا مفتاح دولة**
/// (`IQ-014` الخيار ب · `master-data-design.md` §3.5).
///
/// ★ **وأساس القرار مُعلَن:** أرقام هذا النظام **يمنية دائماً لا دولية**
/// (قرار صاحب المشروع 2026-08-24) — ⟵ **فالمفتاح أقصر وأثبت.**
///
/// الخطوات بترتيبها: ① **توحيد الأرقام** إلى اللاتينية · ② **إسقاط كل ما
/// ليس رقماً** (مسافات · شرطات · أقواس · `+`) · ③ **حذف مفتاح الدولة
/// اليمني** (`+967` · `00967` · `967`) · ④ **حذف الأصفار البادئة**.
///
/// ⚠️★ **وتصحيحٌ لادّعاء كان هنا:** قيل إن ترتيب ③ قبل ④ **ملزم** —
/// ⛔ **وهو غير صحيح، وأثبتت الطفرةُ عكسَه**: بعكس الخطوتين **نجحت
/// الاختبارات السبعة والثمانون كلها**. ★ **والسبب أن الصيغتين تلتقيان على
/// المفتاح نفسه** لأن ⛔ **لا رقم يمني محلي يبدأ بـ`967`.**
/// ✅ **فالترتيب مُبقىً لأنه يُعبِّر عن النيّة** — ⛔ **لا لأنه شرط صحّة.**
///
/// ⛔ **ولا تتحقق هذه الدالة من صحة الرقم ولا طوله** — التحقق عند حدود
/// الإدخال، **وهذه تُنتج المفتاح وحده.**
///
/// ⚠️ **وأثر القرار معلَن:** رقمٌ غير يمني يُخزَّن بأرقامه كما كُتبت **بلا
/// حذف مفتاحه** ⟵ **فمفتاحه صالح ومتفرّد، لكنه غير جاهز للإرسال دولياً.**
String normalizePhone(String value) {
  final StringBuffer digits = StringBuffer();
  for (final int rune in value.runes) {
    final int? digit = _asciiDigitOf(rune);
    if (digit != null) digits.writeCharCode(digit);
  }
  final String local = _stripYemenPrefix(digits.toString());
  return local.replaceFirst(_leadingZeros, '');
}
