/// ═══════════════════════════════════════════════════════════════════════
/// ⛔⛔★★★ **ولماذا في طبقة النطاق لا في شاشة الكشف:**
/// ★ **`design-system.md` §5.1: «القيم تصل الشاشةَ نصوصاً منسَّقة مسبقاً»** —
/// ⟵ **والتفقيط منطقُ تحويلٍ لا تنسيقُ عرض**: ★ **وله قارئان من اليوم**
/// (**الشاشة والمستندُ المُصدَّر PDF**)، ⛔ **ونسخةٌ ثانية منه في أحدهما
/// تُنتج كشفاً وسنداً يقولان مبلغين مختلفين بالحروف عن رقمٍ واحد.**
///
/// ⚠️⚠️ **والتفقيط في مستندٍ يُسلَّم للمقوت ليس زخرفة** — ★ **هو الحارس
/// التقليدي ضد تحريف الرقم**: ⟵ **فخطؤه أسوأ من غيابه**، ⛔ **ولذلك يُختبَر
/// بحالاته الحدّية لا بمثالٍ واحد.**
/// ═══════════════════════════════════════════════════════════════════════
///
/// ★ **والعملة «ريال» بلا كسور** — `ADR-0015`: **كل مبلغ عدد صحيح بالريال**،
/// ⛔ **فلا «هللة» ولا كسرَ يُفقَّط.**
library;

import 'money.dart';

// ═════════════════════════════════════════════════════════════════════════
// معاجم الصيغ — ⛔ **ولا تُبنى نصوصُها بالتركيب اللفظي**
// ═════════════════════════════════════════════════════════════════════════

/// الآحاد المذكَّرة — ★ **والصفر يُعالَج قبلها فلا موضع له هنا**.
const List<String> _ones = <String>[
  '',
  'واحد',
  'اثنان',
  'ثلاثة',
  'أربعة',
  'خمسة',
  'ستة',
  'سبعة',
  'ثمانية',
  'تسعة',
  'عشرة',
  'أحد عشر',
  'اثنا عشر',
  'ثلاثة عشر',
  'أربعة عشر',
  'خمسة عشر',
  'ستة عشر',
  'سبعة عشر',
  'ثمانية عشر',
  'تسعة عشر',
];

/// العشرات — ★ **والمؤشّر هو رقمُ العشرات نفسُه** (2 ⟵ عشرون).
const List<String> _tens = <String>[
  '',
  '',
  'عشرون',
  'ثلاثون',
  'أربعون',
  'خمسون',
  'ستون',
  'سبعون',
  'ثمانون',
  'تسعون',
];

/// المئات — ★ **بصيغها المعتمدة** ⛔ **لا «ثلاث مئة» مركَّبةً بالجمع.**
const List<String> _hundreds = <String>[
  '',
  'مئة',
  'مئتان',
  'ثلاثمئة',
  'أربعمئة',
  'خمسمئة',
  'ستمئة',
  'سبعمئة',
  'ثمانمئة',
  'تسعمئة',
];

/// ★★ صيغُ كلِّ مرتبةٍ ثلاثية — **مفرد · مثنّى · جمعُ قلّة · جمعُ كثرة**.
///
/// ⚠️ **والتمييزُ العربي يتبع العدد لا المرتبة** — ⟵ **«ألفان» و«ثلاثة آلاف»
/// و«أحد عشر ألفاً»**: ★ **ثلاثُ صيغٍ لمرتبةٍ واحدة** ⛔ **لا واحدةٌ تُكرَّر.**
class _ScaleForms {
  const _ScaleForms(this.singular, this.dual, this.plural, this.counted);

  /// واحد — «ألف».
  final String singular;

  /// اثنان — «ألفان».
  final String dual;

  /// من 3 إلى 10 — «آلاف».
  final String plural;

  /// من 11 فأكثر — «ألفاً» (تمييزٌ منصوب مفرد).
  final String counted;
}

/// ★ المراتب الثلاثية من الأصغر — **آحاد ثم ألوف ثم ملايين ثم مليارات**.
const List<_ScaleForms?> _scales = <_ScaleForms?>[
  null, // ★ مرتبةُ الآحاد بلا اسمٍ لها.
  _ScaleForms('ألف', 'ألفان', 'آلاف', 'ألفاً'),
  _ScaleForms('مليون', 'مليونان', 'ملايين', 'مليوناً'),
  _ScaleForms('مليار', 'ملياران', 'مليارات', 'ملياراً'),
];

/// ★ اسمُ المرتبة بحسب عدد مجموعتها — `_ScaleForms` أعلاه.
String _scaleWord(_ScaleForms forms, int group) {
  if (group == 1) return forms.singular;
  if (group == 2) return forms.dual;
  if (group <= 10) return forms.plural;
  return forms.counted;
}

/// ★ يفقّط مجموعةً ثلاثية (1…999) — ⛔ **ولا تُستدعى بصفر.**
String _groupInWords(int group) {
  final List<String> parts = <String>[];
  final int hundreds = group ~/ 100;
  final int rest = group % 100;
  if (hundreds > 0) parts.add(_hundreds[hundreds]);
  if (rest > 0) {
    if (rest < 20) {
      parts.add(_ones[rest]);
    } else {
      final int unit = rest % 10;
      final String tensWord = _tens[rest ~/ 10];
      // ★ **والآحادُ تسبق العشرات في العربية** — «خمسة وعشرون».
      parts.add(unit > 0 ? '${_ones[unit]} و$tensWord' : tensWord);
    }
  }
  return parts.join(' و');
}

/// ★★★ **المبلغ بالحروف العربية مع اسم العملة** — `FR-M17-07`.
///
/// ⛔⛔ **والسالبُ يُصدَّر بكلمة «سالب» صريحة** — ★ **لا بإشارةٍ تُقرأ حرفاً**:
/// ⟵ **ورصيدُ المقوت يكون سالباً فعلاً حين يكون له فائض**
/// (`schema/dealer-ledger.md`: «**الرصيد < 0 ⟸ له فائض**»)،
/// ⛔ **وإسقاطُ الإشارة هنا يقلب معنى المستند رأساً على عقب.**
///
/// ★ **والصفرُ يُفقَّط «صفر ريال»** ⛔ **لا يُترك فارغاً**: ⟵ **فالصفرُ في
/// كشفِ حسابٍ معلومة** («**= 0 ⟸ مسدَّد**») **لا غيابُ قيمة.**
String riyalsInArabicWords(Money amount) {
  final int value = amount.riyals;
  if (value == 0) return 'صفر ريال';

  final bool negative = value < 0;
  // ⚠️ **بلا `abs()`** — ★ `(-2^63).abs()` **تفيض في Dart**: ⟵ **والقسمةُ
  //    على المجموعات تعمل على الموجب المشتقّ من النصّ** ⛔ **لا من `abs`**،
  //    ★ **وهو نفس احتراز [formatRiyals] حرفياً.**
  final BigInt magnitude = BigInt.parse(value.toString().replaceFirst('-', ''));

  final List<int> groups = <int>[];
  BigInt remaining = magnitude;
  final BigInt thousand = BigInt.from(1000);
  while (remaining > BigInt.zero) {
    groups.add((remaining % thousand).toInt());
    remaining = remaining ~/ thousand;
  }

  // ⛔⛔★★ **ومبلغٌ فوق المراتب المعروفة لا يُخمَّن اسمُ مرتبته** — ★ **يُردّ
  //    رقماً صريحاً**: ⟵ **و«تريليون» ليست في المعجم**، ⛔ **واختراعُها في
  //    مستندٍ مالي أسوأ من الاعتراف بحدّه.**
  //
  // ⚠️⚠️ **وحتى في هذا المهرب تبقى الإشارةُ كلمةً** — ★ **رصدَه اختبارُ
  //    الحدّ الأدنى**: ⟵ **و«‎-9223372036854775808 ريال» يضع محرفَ ناقصٍ
  //    لاتينياً في مستندٍ عربيٍّ يُسلَّم للمقوت**، ⛔ **وهو بالضبط ما وُجدت
  //    كلمةُ «سالب» لتمنعه** — ★ **فلا يُستثنى المهربُ من القاعدة.**
  if (groups.length > _scales.length) {
    final String digits = magnitude.toString();
    return negative ? 'سالب $digits ريال' : '$digits ريال';
  }

  final List<String> words = <String>[];
  for (int i = groups.length - 1; i >= 0; i--) {
    final int group = groups[i];
    if (group == 0) continue;
    final _ScaleForms? forms = _scales[i];
    if (forms == null) {
      words.add(_groupInWords(group));
      continue;
    }
    // ★ **والواحدُ والاثنان لا يُذكَر عددُهما** — «ألف» لا «واحد ألف».
    if (group == 1 || group == 2) {
      words.add(_scaleWord(forms, group));
    } else {
      words.add('${_groupInWords(group)} ${_scaleWord(forms, group)}');
    }
  }

  final String spelled = words.join(' و');
  return negative ? 'سالب $spelled ريال' : '$spelled ريال';
}
