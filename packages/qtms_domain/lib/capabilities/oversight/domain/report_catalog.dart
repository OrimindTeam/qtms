/// ⟵ **فالعائلةُ عقدُ تفويضٍ لا ترويسةُ عرض.**
/// ═══════════════════════════════════════════════════════════════════════
///
/// ⚠️ **ورمزُ التقرير (`R-01`) معرّفٌ داخلي لا نصُّ واجهة** — ★ **يُكتب في
/// `entityId` عند التصدير** (`FR-M19-04`)، ⛔ **ولا يُعرَض في شاشة**
/// (`ui-guidelines.md` §6: **لا كلمة إنجليزية في أي شاشة**).
library;

import '../../identity_access/domain/permission.dart';

/// عائلةُ تقارير — ★ **ولكلٍّ مفتاحُ صلاحيةٍ مستقل** (`IQ-034` الخيار ب).
///
/// ⚠️⚠️ **و«لكلِّ تقريرٍ على حدة» في `FR-M19` §4 تُقرأ قراءةً موسَّعة** —
/// ★ **أثرٌ معلَنٌ في `reporting-design.md` §6** ⛔ **لا مسكوتٌ عنه:**
/// ⟵ **فمن يرى «المخزنية» يرى `R-01`…`R-07` كلَّها.**
enum ReportFamily {
  /// مخزنية — `R-01`…`R-07`.
  inventory(Permission.reportInventoryView, 'التقارير المخزنية'),

  /// بيعية — `R-08`…`R-13`.
  sales(Permission.reportSalesView, 'التقارير البيعية'),

  /// مالية — `R-14`…`R-20`.
  financial(Permission.reportFinancialView, 'التقارير المالية'),

  /// السحبيات والخرجيات — `R-21`…`R-24`.
  outflow(Permission.reportOutflowView, 'تقارير السحبيات والخرجيات'),

  /// الرعية — `R-25`…`R-27`.
  supplier(Permission.reportSupplierView, 'تقارير الرعية'),

  /// رقابية — `R-28`…`R-31`.
  oversight(Permission.reportOversightView, 'التقارير الرقابية');

  const ReportFamily(this.requiredPermission, this.label);

  /// ★ المفتاح الذي لا تُفتَح تقاريرُ العائلة بدونه.
  ///
  /// ⚠️⚠️ **وهو بوابةُ وصولٍ إلى الشاشة** — ★ **وسريّةُ الأرقام نفسِها
  /// يحرسها شرطُ قراءةِ كلِّ مجموعةٍ ونطاقُ المصادر** (`GR-23`)،
  /// ⛔ **فلا يُقرأ هذا المفتاح ضماناً لما لا تضمنه القاعدة**
  /// (`permissions-catalog.md` §2.11 · `RISK-02`).
  final Permission requiredPermission;

  /// ★ الاسم المعروض — **من `FR-M19` §2 حرفياً**.
  final String label;
}

/// ★★ التقارير المبنيّة فعلاً — **ستةٌ وعشرون من واحدٍ وثلاثين**.
///
/// ⛔ **ولا يُضاف عضوٌ هنا قبل بناء بانيه ومصدرِ بياناته** — راجع ترويسة
/// الملف.
enum ReportId {
  // ════════════════════════════ مخزنية ════════════════════════════
  /// `R-01` — حركة نوع تفصيلية · **النوع والفترة** (`FR-M19` §2).
  itemMovements('R-01', 'حركة نوع تفصيلية', ReportFamily.inventory),

  /// `R-02` — رصيد المخزون الحالي · **النوع والحالة**.
  currentStock('R-02', 'رصيد المخزون الحالي', ReportFamily.inventory),

  /// `R-03` — الوارد عدداً · **الفترة والنوع والرعوي**.
  countedIntakes('R-03', 'الوارد عدداً', ReportFamily.inventory),

  /// `R-04` — الوارد جواني · **الفترة والرعوي والجونية**.
  sackIntakes('R-04', 'الوارد جواني', ReportFamily.inventory),

  /// `R-05` — متبقي اليوم لكل نوع · **التاريخ والنوع**.
  todayRemainder('R-05', 'متبقي اليوم لكل نوع', ReportFamily.inventory),

  /// ★★ `R-07` — **الوزن الضائع والسكرب والإتلاف** · **الفترة والرعوي**
  /// (`WU-020`).
  ///
  /// ⛔⛔★★★ **وثلاثةُ بنودٍ في تقريرٍ واحد لأن `FR-M19` §2 يُسمّيه هكذا
  /// حرفياً** — ⟵ **وما يجمعها قاعدةٌ واحدة لا تصنيفٌ شكليّ:** ★ **كلُّها
  /// خروجٌ بلا استحقاقٍ للرعوي ولا مدخلٍ في سعر الجونية** (`A-15` ·
  /// `design-overview.md` §2.2)، ⛔ **والسكربُ ثالثُها لأنه يخرج من الوزن
  /// المطالب به قبل احتسابه** (§2.2: «**المطالب به = الكلي − الثلج −
  /// السكرب**»).
  ///
  /// ⚠️⚠️ **وكان مؤجَّلاً حتى هذه الزيادة بقرارٍ معلَن لا سهو** — ★ **لأن
  /// «الإتلاف» في عنوانه لم يكن له كاتبٌ في النظام**: ⟵ **وبناؤه قبلها
  /// كان يَعِد بما لا يفعل** ([`DEBT-72`]).
  wasteAndDisposal(
    'R-07',
    'الوزن الضائع والسكرب والإتلاف',
    ReportFamily.inventory,
  ),

  // ════════════════════════════ بيعية ════════════════════════════
  /// `R-08` — التوزيعات التفصيلية · **الفترة والمقوت والنوع**.
  distributions('R-08', 'التوزيعات التفصيلية', ReportFamily.sales),

  /// `R-09` — ملخص التوزيع لكل مقوت · **الفترة**.
  dealerDistributionSummary(
    'R-09',
    'ملخص التوزيع لكل مقوت',
    ReportFamily.sales,
  ),

  /// `R-10` — الضمارات · **الفترة والمقوت والحالة**.
  settlements('R-10', 'الضمارات', ReportFamily.sales),

  /// `R-11` — المبيعات النقدية المباشرة · **الفترة والنوع**.
  cashSales('R-11', 'المبيعات النقدية المباشرة', ReportFamily.sales),

  /// `R-12` — المبيعات حسب النوع · **الفترة**.
  salesByItem('R-12', 'المبيعات حسب النوع (كمية وقيمة)', ReportFamily.sales),

  /// `R-13` — السطور غير المسعَّرة · **الفترة والمقوت**.
  unpricedLines('R-13', 'السطور غير المسعَّرة', ReportFamily.sales),

  // ════════════════════════════ مالية ════════════════════════════
  /// `R-14` — المقبوضات · **الفترة وحالة الإيداع**.
  receipts('R-14', 'المقبوضات', ReportFamily.financial),

  /// `R-15` — الخصومات · **الفترة**.
  discounts('R-15', 'الخصومات', ReportFamily.financial),

  /// `R-16` — حركة النقد في تاريخ · **التاريخ**.
  ///
  /// ⚠️ **ولا مفتاحَ زائدٌ له** — ★ **بنودُه المحكومة تُخفى بالإسقاط**
  /// (`projectCashMovement`)، ⛔ **ولا يُرَدُّ استعلامُه لغيابها** (`E-29`).
  cashMovement('R-16', 'حركة النقد في تاريخ', ReportFamily.financial),

  /// `R-17` — أرصدة المقاوته · **الحالة والحد الأدنى للرصيد**.
  dealerBalances('R-17', 'أرصدة المقاوته', ReportFamily.financial),

  /// `R-19` — كشف حساب مقوت · **المقوت والفترة**.
  dealerStatement('R-19', 'كشف حساب مقوت', ReportFamily.financial),

  /// `R-20` — ضمار المالك اليومي · **الفترة**.
  ///
  /// 🔒 **ويقرأ `daily_summaries` وشرطُها `ownerLedgerView`** — ⟵ **فهو
  /// مفتاحٌ زائدٌ على مفتاح العائلة** ⛔ **وبدونه يُرَدُّ الاستعلامُ دائماً.**
  ownerLedgerDaily(
    'R-20',
    'ضمار المالك اليومي',
    ReportFamily.financial,
    extraPermissions: <Permission>[Permission.ownerLedgerView],
  ),

  // ═══════════════════════ السحبيات والخرجيات ═══════════════════════
  /// `R-21` — سجل السحبيات · **الفترة والفئة ونوع البند**.
  ///
  /// 🔒 **وشرطُ قراءة `outflows` يتفرّع على `ledgerType`** ([`DEBT-89`]).
  withdrawals(
    'R-21',
    'سجل السحبيات (المالك)',
    ReportFamily.outflow,
    extraPermissions: <Permission>[Permission.withdrawalView],
  ),

  /// `R-22` — سجل الخرجيات · **الفترة والفئة ونوع البند**.
  expenses(
    'R-22',
    'سجل الخرجيات (التشغيلية)',
    ReportFamily.outflow,
    extraPermissions: <Permission>[Permission.expenseView],
  ),

  /// `R-23` — الأثر النهائي على حساب المصدر · **الفترة والمصدر**.
  ///
  /// 🔒 **ومفتاحُه المستقل `sourceNetImpactView`** — **الكتالوج §2.7 يُسمّيه
  /// بـ`R-23` حرفياً** · ★ **ويقرأ `daily_summaries` فيلزم `ownerLedgerView`.**
  sourceNetImpact(
    'R-23',
    'الأثر النهائي على حساب المصدر',
    ReportFamily.outflow,
    extraPermissions: <Permission>[
      Permission.ownerLedgerView,
      Permission.sourceNetImpactView,
    ],
  ),

  /// `R-24` — تغطية السحبيات من المقبوض · **التاريخ**.
  ///
  /// ⚠️ **والنسبةُ على المقبوض لا على الواصل** — `GR-47` · `FR-M15-19`.
  withdrawalCoverage(
    'R-24',
    'تغطية السحبيات من المقبوض اليومي',
    ReportFamily.outflow,
  ),

  // ════════════════════════════ الرعية ════════════════════════════
  /// `R-25` — حساب الرعوي لكل مصدر · **الفترة والرعوي والمصدر**.
  supplierAccount(
    'R-25',
    'حساب الرعوي لكل مصدر',
    ReportFamily.supplier,
    extraPermissions: <Permission>[Permission.supplierFinanceView],
  ),

  /// `R-26` — الضريبة المستحقة · **الفترة والرعوي**.
  supplierTax(
    'R-26',
    'الضريبة المستحقة',
    ReportFamily.supplier,
    extraPermissions: <Permission>[Permission.supplierFinanceView],
  ),

  /// `R-27` — تفكيك سعر جونية · **الجونية**.
  ///
  /// 🔒⛔⛔★★ **ومفتاحا السحبيات والخرجيات شرطٌ لازم لا تجميل:** ★ **التفكيك
  /// يقرأ حركات الجونية من `distributions` و`cash_sales` و`outflows`
  /// بنوعيها** ([`DEBT-89`])، ⟵ **واستعلامُ `outflows` يُرَدُّ كاملاً لمن
  /// لا يملك مفتاحَ نوعه** — ⛔ **فتقريرٌ بلا المفتاحين يُرَدُّ دائماً**،
  /// ★ **أو يُنقِص سعرَ الجونية بصمت** ⛔ **وهو أسوأ.**
  sackPriceBreakdown(
    'R-27',
    'تفكيك سعر جونية',
    ReportFamily.supplier,
    extraPermissions: <Permission>[
      Permission.withdrawalView,
      Permission.expenseView,
    ],
  ),

  // ═══════════════════════════ رقابية ═══════════════════════════
  /// `R-28` — الإدخالات المعلّقة · **النوع والفترة**.
  pendingEntries('R-28', 'الإدخالات المعلّقة', ReportFamily.oversight);

  const ReportId(
    this.code,
    this.title,
    this.family, {
    this.extraPermissions = const <Permission>[],
  });

  /// ★ الرمز المعتمد في `FR-M19` §2 — ⛔ **معرّفٌ لا نصُّ واجهة**.
  final String code;

  /// ★ العنوان المعروض — **من `FR-M19` §2 حرفياً**.
  final String title;

  /// العائلة — ★ **ومنها مفتاحُ الصلاحية**.
  final ReportFamily family;

  /// ★★★ مفاتيحُ زائدةٌ على مفتاح العائلة — ⛔ **وكلُّها شرطُ قراءةٍ فعلي**.
  ///
  /// ═════════════════════════════════════════════════════════════════════
  /// ⛔⛔★★ **ولا يُوضَع هنا مفتاحٌ «للاحتياط»** — ★ **كلُّ مفتاحٍ هنا يُقابل
  /// شرطَ قراءةٍ في `firestore.rules` يُرَدُّ استعلامُ التقرير بدونه كاملاً**
  /// (`IQ-024` · [`DEBT-89`]): ⟵ **فعرضُ تقريرٍ يُرَدُّ استعلامُه دائماً
  /// يُري المستخدم عطلاً لا منعاً**، ⛔ **وحجبُ تقريرٍ يعمل يمنعه بلا سبب.**
  ///
  /// ★ **والاستثناء المعلَن `sourceNetImpactView`** — **مفتاحُ عرضٍ بلا شرطٍ
  /// في القواعد** (`permissions-catalog.md` §5 — **مستثنى بمبرر**):
  /// ⟵ **ويُقرأ هنا لأن الكتالوج يُسمّيه بـ`R-23` نصّاً.**
  /// ═════════════════════════════════════════════════════════════════════
  final List<Permission> extraPermissions;

  /// ★★ كلُّ ما يلزم لفتح هذا التقرير — **مفتاحُ عائلته وما زاد عليه**.
  List<Permission> get requiredPermissions => <Permission>[
        family.requiredPermission,
        ...extraPermissions,
      ];

  /// ★ يقرأ التقرير من رمزه — و`null` **لرمزٍ لا يعرفه هذا الإصدار**.
  ///
  /// ⛔ **ولا يُقرأ بافتراضٍ آمن:** ★ **رمزٌ مجهول يُعرَض غياباً صريحاً**
  /// ⛔ **ولا يُفتَح على تقريرٍ آخر** (نفس منطق `PendingDocumentKind.tryParse`).
  static ReportId? tryParse(String? raw) {
    for (final ReportId report in ReportId.values) {
      if (report.code == raw) return report;
    }
    return null;
  }
}

/// ★★ تقاريرُ عائلةٍ واحدة — **بترتيب `FR-M19` §2**.
List<ReportId> reportsOfFamily(ReportFamily family) => <ReportId>[
      for (final ReportId report in ReportId.values)
        if (report.family == family) report,
    ];
