/// إجراءات سجل التدقيق — **نقل حرفي لـ`audit-log-design.md` §3**.
///
/// ★ **المصدر:** حقل `action` هناك يعدّد: «إنشاء · **تعديل** · إلغاء ·
/// تعطيل · دخول · تصدير · **تأكيد إيداع بنكي** · **تأكيد وزن ضائع** ·
/// **إتلاف** · **تصريف متأخر** · تغيير صلاحية».
///
/// ★ **والأسماء الإنجليزية من معجم `naming-conventions.md` §2 حصراً** —
/// `disposal` للإتلاف · `agedRemainder` للمتبقي المتأخر · `permission`
/// للصلاحية التفصيلية. ⛔ **ولا مرادف مخترَع.**
library;

/// الإجراء المُسجَّل في قيد التدقيق.
///
/// ⛔ **لا يُضاف عنصر هنا بلا سطر في `audit-log-design.md` §3** — نفس منطق
/// `BR-M1-07` في مفاتيح الصلاحيات: القائمة المزدوجة تفترق عند أول إضافة.
enum AuditAction {
  /// إنشاء مستند أو سجل.
  create,

  /// تعديل مباشر — ★ **يشترط سبباً نصياً** (`ADR-0004`).
  amend,

  /// إلغاء مستند — **وسماً لا حذفاً** (`ADR-0004` · القاعدة 10).
  cancel,

  /// تعطيل مستخدم أو كيان — **بديل الحذف** (`authentication-policy.md` §2).
  disable,

  /// تسجيل دخول.
  signIn,

  /// تصدير بيانات.
  export,

  /// تأكيد الإيداع البنكي — **مسار مقيَّد بملاحظة إلزامية**.
  depositConfirm,

  /// تأكيد الوزن الضائع.
  lostWeightConfirm,

  /// الإتلاف — ★ **بلا أي أثر مالي**.
  disposal,

  /// تصريف متبقٍ متأخر — ★ **المسار الوحيد الذي يقبل تاريخ مخزون أقدم**.
  agedRemainderClear,

  /// تغيير صلاحية أو نطاق مصادر — `authentication-policy.md` §3
  /// («**كل تغيير صلاحية يترك قيداً في سجل التدقيق**»).
  permissionChange,

  /// ★★ **حذف قالب دور غير مُسنَد** — `IQ-018` (2026-08-24).
  ///
  /// ⛔★★ **وهو الحذف الوحيد في النظام كله، ولا يُقاس عليه غيره:**
  /// `security-requirements.md` §2 البند 1 يمنع الحذف في **السجلات
  /// والحركات** — ★ **وقالب الدور غير المُسنَد ليس واحداً منها**: لا حركة
  /// فيه ولا مستخدم يشير إليه، ⟵ **فلا مرجع ينكسر ولا تاريخ يضيع**.
  ///
  /// ⚠️ **ولماذا فعلٌ مستقل لا [cancel]:** الإلغاء **وسمٌ لا حذف**
  /// (`ADR-0004` القاعدة 10) — والمستند يبقى بعده. ⟵ **وتسميةُ الحذف
  /// إلغاءً كانت ستجعل السجل يقول «أُلغي» عن مستندٍ لم يعد موجوداً**،
  /// ★ **فيبحث المدقّق عمّا لا يجده ويظنّه عطلاً.**
  delete,
}
