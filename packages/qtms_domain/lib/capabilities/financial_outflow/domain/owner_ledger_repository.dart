/// عقد قراءة ضمار المالك وحركة النقد — ⛔ **قراءةً فقط بلا استثناء**.
///
/// ═══════════════════════════════════════════════════════════════════════
/// ⛔⛔★★★ **ولا دالةَ كتابةٍ واحدة في هذا الملف — وهو قيدٌ بنيويٌّ لا سهو:**
/// ★ **الملخصاتُ تبنيها السحابة وحدها** (`schema/daily-summaries.md` القاعدة
/// 6 · `api-overview.md` §4 «الكتابة الممنوعة من التطبيق: … الملخصات»)،
/// ⟵ **والمجموعتان `allow write: if false` لكل مستخدمٍ بمن فيهم المالك**
/// (`ADR-0013`). ★ **فعقدُ كتابةٍ هنا كان وعداً لا يمكن الوفاء به.**
///
/// ⛔⛔★★ **وكلُّ استعلام سردٍ يُقيّد `sourceId` صراحةً** — ★ **شرطُ قراءة
/// `daily_summaries` يعتمد `resource.data`** (`storedInScope()` **وقيمةُ
/// `all` تشترط `allSourcesCardView`**): ⟵ **والشرط يُقيَّم على قيود
/// الاستعلام لا على كل مستند** (`IQ-024` · `WU-008` · [`DEBT-89`])،
/// ⛔ **فاستعلامٌ لا يُقيّده يُرفَض كاملاً ولو ملك القارئُ كلَّ المفاتيح.**
/// ═══════════════════════════════════════════════════════════════════════
library;

import '../../../core/calendar_day.dart';
import 'owner_ledger_summary.dart';

/// دليلُ قراءة الملخصات — ★ **بثٌّ لحظي** (`FR-M15-13` · `ADR-0003`).
abstract interface class OwnerLedgerDirectory {
  /// ⛅ يبثّ ملخّصَ مصدرٍ في يوم — ★ **و`null` ليومٍ بلا ملخّصٍ مكتوب.**
  ///
  /// ⛔⛔ **والغيابُ ليس خطأً:** ★ **يومٌ بلا حركةٍ لا يُكتب له مستند**،
  /// ⟵ **ويُعرَض بأصفارٍ صريحة لا شرطات** (`ui-guidelines.md` نمط 1 —
  /// **«لأن الصفرَ هنا معلومة»**).
  Stream<OwnerLedgerSummary?> watchSummary({
    required String sourceId,
    required CalendarDay date,
  });

  /// ⛅ يبثّ سلسلةَ آخر سبعةِ أيام لمصدر — ★ **قراءةٌ واحدة** (§2.1 القاعدة 3).
  Stream<List<OwnerLedgerTrendPoint>> watchTrend({required String sourceId});

  /// ⛅ يقرأ ملخصاتِ مدىً من الأيام لمصدر — `FR-M15-14` (**سجل الأيام**).
  ///
  /// ★ **مرتَّبةٌ تنازلياً بالتاريخ** — الفهرس `sourceId ↑ · date ↓`.
  Stream<List<OwnerLedgerSummary>> watchSummaryRange({
    required String sourceId,
    required CalendarDay from,
    required CalendarDay to,
  });
}

/// قارئُ حركة النقد في تاريخ — ★ **يُجمَع من الدفاتر لا من ملخّص**.
///
/// ⚠️⚠️★★ **ولماذا لا ملخّصَ مبنيٌّ مسبقاً لها:** ★ **`daily_summaries`
/// مُعرَّفٌ بالبنود العشرة وحدها** (`schema/daily-summaries.md`)، ⛔ **ولا
/// حقلَ فيه لحركة النقد** — ⟵ **وإضافةُ حقولٍ إليه اختراعُ مخطَّطٍ لا يُقرّه
/// مستند.** ★ **والشاشةُ تُفتَح عند الطلب لا عشراتِ المرات يومياً** (§8
/// تُبرِّر البناء المسبق ببطاقةٍ تُفتَح باستمرار)، ⟵ **فالتجميعُ عند القراءة
/// هنا اتساقٌ مع `ADR-0008`** ⛔ **لا مخالفةٌ للأداء.**
/// ⛔⛔★★ **وقراءةٌ عند الطلب لا بثٌّ لحظي** — ★ **والفرقُ مقصود:**
/// ⟵ **الشاشةُ تُفتَح بتاريخٍ يختاره المستخدم** (`FR-M15-22`)، ★ **وتجميعُها
/// أربعةُ استعلاماتٍ لكل مصدر**: ⛔ **وبثُّها لحظياً كان يُعيد التجميع كلَّه
/// عند كل كتابةٍ في أيٍّ منها.**
/// ⚠️⚠️★★ **وكلُّ مزوّدِ قراءةٍ عند الطلب `autoDispose`** — [`DEBT-90`]
/// (2026-09-03): ★ **وإلا خُزِّنت النتيجةُ بمفتاح العائلة فأعادت تفكيكاً
/// قديماً بعد حركةٍ حقيقية** — ⛔ **مخالفةٌ لـ`ADR-0008`.**
abstract interface class CashMovementReader {
  /// ⛅ يقرأ حركةَ النقد في تاريخٍ لمجموعة مصادر.
  ///
  /// ★ **[sourceIds] مصدرٌ واحدٌ أو كلُّ مصادر القارئ** (`FR-M15-22`).
  ///
  /// ⛔⛔★★ **و[includesUnscopedSurplus] للنطاق الشامل وحده** — ★ **الفائضُ
  /// العام لا يُنسَب لمصدر** (`FR-M12-12`: **`sourceId` فيه `null` عمداً**):
  /// ⟵ **فيظهر في «كل المصادر» وحدها**، ⛔ **ونسبتُه لمصدرٍ مُخمَّن تُضخِّم
  /// صندوقَه بمالٍ لا يخصّه.**
  ///
  /// ★ **و[readsDeposit] من صلاحية `receiptDepositView`** — ⛔ **ولا تُقرأ
  /// مستنداتُ الإيداع لمن لا يملكها** (`ADR-0017`).
  Future<CashMovementSummary> readCashMovement({
    required List<String> sourceIds,
    required bool includesUnscopedSurplus,
    required CalendarDay date,
    required bool readsDeposit,
  });
}
