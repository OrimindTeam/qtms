/// صياغة التواريخ والأوقات المعروضة — ★ **مصدر حقيقة واحد للتطبيق كله**.
///
/// ⛔⛔★★ **ولا نسخةَ ثانية منها في شاشة:** `design-system.md` §8 المحظور
/// الحادي عشر («نسخُ مكوّن بدل إعادة استخدامه») و`coding-standards.md` §2.2
/// — ★ **وصيغتان للتاريخ في شاشتين تُقرآن رقمين مختلفين للحدث نفسه.**
///
/// ★★ **والأرقام لاتينية (0-9) قيمةً وحيدة ثابتة** (`AM-003` ·
/// `rtl-ltr-guidelines.md`) — ⛔ **لا خياراً ولا أرقاماً هندية.**
library;

import 'package:qtms_domain/qtms_domain.dart';

/// ★ تاريخ مقروء — `YYYY/MM/DD` بالأرقام اللاتينية.
String dayLabel(CalendarDay day) =>
    '${day.year}/${_two(day.month)}/${_two(day.day)}';

/// ★★ لحظةٌ مقروءة — `YYYY/MM/DD HH:MM` **بتوقيت النظام نفسه (UTC)**.
///
/// ═══════════════════════════════════════════════════════════════════════
/// ⚠️⚠️ **ولماذا UTC لا وقت الجهاز — وهو قرارٌ تنفيذي مُعلَن لا نقلٌ عن مستند:**
///
/// `data-dictionary.md` §5 يجعل `occurredAt` **«بتوقيت الخادم»** ⛔ **ولا
/// يذكر منطقةَ عرضه.** ★ **ويومُ هذا النظام كلُّه UTC**: قواعد الحماية تقارن
/// تاريخ المخزون بـ`request.time.date()` **وهي تقتطع إلى منتصف ليل UTC**
/// (`CalendarDay.asUtcMidnight`)، **والعدّاد اليومي والمفاتيح المركّبة كلها
/// مبنيةٌ على ذلك اليوم.**
///
/// ⟵ ★ **فعرضُ وقتٍ محلّي كان سيُظهر قيداً بتاريخٍ يخالف `stockDate` الخاص
/// به نفسه** في الساعات الأولى من الليل (اليمن `UTC+3`) — ⛔ **فيقرأ
/// المدقّق أن حركةً وقعت في يومٍ وسُجِّلت في آخر**، ★ **وهو أسوأ التباسٍ
/// ممكن في سجلٍّ هو الحافظ الوحيد للتاريخ** (`RISK-05`).
///
/// ⛔ **والمقايضة معلَنة:** المستخدم يقرأ وقتاً يسبق ساعةَ جداره بثلاث
/// ساعات — ★ **وهو ثمنٌ مقبول مقابل اتساق التاريخ عبر النظام كله**،
/// ⛔ **بينما العكس كان يُنتج تناقضاً لا يفسّره أحد.**
/// ═══════════════════════════════════════════════════════════════════════
String timestampLabel(DateTime instant) {
  final DateTime utc = instant.toUtc();
  return '${dayLabel(CalendarDay.fromUtc(utc))} '
      '${_two(utc.hour)}:${_two(utc.minute)}';
}

String _two(int value) => value.toString().padLeft(2, '0');
