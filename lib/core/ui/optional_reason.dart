/// يُعيد النص مقصوصاً، أو `null` إن كان فارغاً أو فراغات وحدها.
///
/// ⛔ **والفراغات ليست سبباً** — ★ **فتُقرأ غياباً لا نصّاً فارغاً**، ⟵ **فلا
/// يُخزَّن في القيد حقلٌ يبدو مملوءاً وهو خالٍ** (`ADR-0020` القيد 3).
///
/// ★★ **ونظيرُه في طبقة النطاق `AuditEntry` يحرس الطرف الآخر** — ⟵ **فحتى
/// لو تسلّل فراغٌ من مسارٍ آخر لا يصل التخزين نصّاً فارغاً.**
String? blankToNull(String? text) {
  final String? trimmed = text?.trim();
  return (trimmed == null || trimmed.isEmpty) ? null : trimmed;
}
