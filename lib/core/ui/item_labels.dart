/// ★★★ **اسمُ النوع كما يُعرَض** — `AM-012` §4.4 (2026-09-02).
///
/// ═══════════════════════════════════════════════════════════════════════
/// ⛔⛔★★★ **مصدرُ حقيقةٍ واحد لصيغة الاسم** — ★ **يقرؤه كلُّ ما يعرض نوعاً:**
/// ⟵ **شاشةُ الأنواع، وخياراتُ الإدخال في التوريد والتوزيع والبيع النقدي
/// والسحبيات** — ⛔ **ونسخةٌ في كلٍّ منها تفترق عند أول تعديل**
/// (`coding-standards.md` §2.2 · `design-system.md` §8 المحظور الحادي عشر).
///
/// ★★ **ودالةٌ خالصة بلا قراءةِ مزوّد** — ⟵ **فتُختبَر بلا شجرةِ ويدجت**،
/// ★ **والتفضيلُ يُمرَّر إليها** (`showPieceWeightProvider`).
/// ═══════════════════════════════════════════════════════════════════════
library;

import 'package:qtms_domain/qtms_domain.dart';

/// ★★★ **اسمُ النوع مع وزن الحبة عند تفعيل الخيار** — `AM-012` §4.4.
///
/// ```text
/// مفعَّل   ·  وزنيٌّ بوزن حبة  ⟶  'بطّوه وزن (200 جرام)'
/// مفعَّل   ·  عدديٌّ بلا وزن   ⟶  'عود'
/// معطَّل   ·  أيّاً كان        ⟶  'بطّوه'
/// ```
///
/// ═══════════════════════════════════════════════════════════════════════
/// ⛔⛔★★★ **وهو خيارُ عرضٍ محضٌ لا يمسّ طبيعةَ النوع بحرف** — **بنصِّ الطلب:**
/// «**هذا الخيار تجميلي/عرضي فقط، ولا يؤثر إطلاقاً على الطبيعة العددية
/// للنوع؛ يستمر ظهوره كـعدد في كل التقارير والشاشات**».
/// ⟹ ★ **فالكميةُ تبقى بوحدتها من `unitOfItem`** (`quantityLabel`)،
/// ⛔ **ولا يُشتقّ من هذا النصِّ حسابٌ ولا وحدة.**
///
/// ⛔⛔★★★ **ولا يُستنتَج وزنُ حبةٍ غائب من شيء إطلاقاً** — `FR-M7-14` · `E-08`:
/// ★ **الغائبُ يُسقِط اللاحقةَ ولا شيءَ غير ذلك** ⟵ **ولا قسمةَ وزنٍ كلي
/// على عدد**، ⛔ **وهي القاعدةُ التي يحرسها النظام في ثلاثة مواضع.**
///
/// ★ **وللأنواع العددية لا وزنَ حبةٍ أصلاً** (`E-09`: **الحقل مقفل**) —
/// ⟵ **فتظهر بأسمائها وحدها ولو كان الخيار مفعَّلاً**، ⛔ **ولا صفرَ يُطبَع.**
/// ═══════════════════════════════════════════════════════════════════════
///
/// ⚠️ **ووزنُ حبةٍ غيرُ صحيحٍ يُعرَض بكسره** — ★ **`data-dictionary.md` يجعله
/// عشرياً** (⛔ **بخلاف المبالغ التي هي `int` دائماً** — `ADR-0015`):
/// ⟵ **و`200.0` تُعرَض «200»**، ★ **و`12.5` تُعرَض «12.5»** ⛔ **ولا تُقرَّب.**
String itemDisplayName(
  String name, {
  required bool showPieceWeight,
  double? pieceWeightGrams,
}) {
  if (!showPieceWeight) return name;
  final double? grams = pieceWeightGrams;
  // ⛔ **والصفرُ والسالبُ وغيرُ المنتهي ليست أوزاناً** — ★ **نفسُ حارس
  //   `validateItem`** (`FR-M5-02`): ⟵ **فتُسقَط اللاحقة** ⛔ **ولا تُطبَع
  //   «وزن (0 جرام)»** ★ **وهي تقول ما ليس صحيحاً.**
  if (grams == null || !grams.isFinite || grams <= 0) return name;
  return '$name وزن (${_grams(grams)} جرام)';
}

/// ★ اسمُ النوع من بطاقته — ★ **الصيغةُ نفسُها** ⛔ **بلا تكرار.**
String itemCardDisplayName(ItemCard item, {required bool showPieceWeight}) =>
    itemDisplayName(
      item.name,
      showPieceWeight: showPieceWeight,
      pieceWeightGrams: item.pieceWeightGrams,
    );

/// ★ الجرامات نصّاً — ⛔ **بلا كسرٍ صفريّ زائد.**
///
/// ★★ **والأرقام لاتينية (0-9) قيمةً وحيدة ثابتة** (`AM-003`).
String _grams(double grams) {
  // ★ **والصحيحُ بلا فاصلة** — ⟵ **«200» لا «200.0»**: ⛔ **والكسرُ الصفريّ
  //   في اسمِ صنفٍ ضجيجٌ يقرؤه المستخدم دقّةً لا وجود لها.**
  if (grams == grams.roundToDouble()) return grams.round().toString();
  return grams.toString();
}
