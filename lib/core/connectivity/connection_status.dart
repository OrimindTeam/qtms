/// ★★★ **حالة الاتصال — مقيسةٌ لا مُدَّعاة** (`ui-guidelines.md` §3-أ القاعدة 3).
///
/// ⛔⛔★★★ **ولماذا نوعٌ ثلاثيُّ الحالات لا `bool`:** ★ **`bool` يُجبر
/// اللحظةَ الأولى على الكذب** — ⟵ **فإمّا وُسِمَت «متصل» قبل أي قياس**
/// (**ادّعاءٌ لا معلومة، وهو ضدُّ ما وُجد المؤشّر لأجله**) **وإمّا «غير
/// متصل»** ⟵ **فيُقرأ عطلاً في كل إقلاع.** ★ **و[ConnectionStatus.unknown]
/// تقول الحقيقة: لم يصل قياسٌ بعد.**
///
/// ⚠️⚠️ **وهذا عرضٌ لا حماية:** ★ **`ADR-0003` يمنع الحفظ المحلي أصلاً**،
/// ⟵ **فالكتابة تفشل من تلقائها عند الانقطاع** — ★ **والمؤشّر يجعل الفشل
/// متوقَّعاً قبل بدء العملية لا مفاجأةً بعدها.**
library;

/// حالة الاتصال بخادم البيانات.
enum ConnectionStatus {
  /// ★ **قياسٌ لم يصل بعد** — ⛔ **ولا يُعرَض «متصل» ولا «غير متصل».**
  unknown,

  /// ★ **بثٌّ حيٌّ يصل من الخادم فعلاً.**
  online,

  /// ⛔ **الخادم غير بالغ** — ★ **والحفظ سيفشل.**
  offline,
}

/// ★★ مصدرُ حالة الاتصال — ⛔ **يُحقَن في الجذر ولا يُبنى في شاشة**
/// (`ADR-0010` — حقن اعتمادية صريح).
///
/// ⛔⛔★★ **ولا يُقاس بوجود واجهة شبكةٍ على الجهاز:** ★ **جهازٌ على شبكةٍ
/// بلا نفاذٍ إلى الخادم يُوسَم «متصل» زوراً** — ⟵ **والمقياس الوحيد الصادق
/// هو بلوغُ الخادم نفسِه.**
abstract interface class ConnectionMonitor {
  /// بثٌّ حيٌّ لحالة الاتصال — ★ **يبدأ بـ[ConnectionStatus.unknown].**
  Stream<ConnectionStatus> watch();
}
