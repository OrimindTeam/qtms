/// ═══════════════════════════════════════════════════════════════════════
/// ⛔⛔★★★ **وهي المخالفةُ المحتملةُ الوحيدة في هذا التعديل — فتُقرأ بحرفها:**
///
/// ★ **`authentication-policy.md` §6 «ما لا نفعله» يقول حرفياً:** «**حفظ بيانات
/// الاعتماد محلياً _بلا حماية النظام_**» — ⟹ ★★★ **فالمنعُ مقيَّدٌ بقيدٍ
/// صريحٍ لا مطلق**، ⛔ **ولولا ذلك لكُتب مطلقاً كما كُتبت أخواتُه الثلاث في
/// الجدول نفسِه** («تسجيلٌ ذاتي مفتوح» · «دخولُ ضيف» · «تجاوزُ المصادقة في
/// بيئة التطوير») — ★ **وهي كلُّها بلا قيد.**
///
/// ⛔⛔★★★ **و«حمايةُ النظام» هنا مُسمّاةُ الآلية لا وصفٌ فضفاض:**
/// **`AES/GCM` بمفتاحٍ ملفوفٍ داخل `Android Keystore`** — ★ **وهو الشرط 1
/// من الأحد عشر في `ADR-0024`** ⛔ **ولا تُقبَل آليةٌ أدنى**، ★ **والقياسُ
/// على مصدر الحزمة في `secure_credential_vault.dart`.**
///
/// ⛔⛔★★★ **والشرط 2 مفروضٌ ببنية هذه الواجهة نفسِها لا بمراجعة:**
/// ★ **[CredentialVault.readIfPresent] لا تُستدعى إلا بعد نجاح مصادقةٍ بيومترية** —
/// ⟵ **والحارسُ في `biometricLoginControllerProvider`** ⛔ **لا هنا**:
/// ★ **فالخزنةُ مخزنٌ محضٌ بلا سياسة** (`ADR-0009`: ⛔ **لا منطق في
/// البنية التحتية**)، ⟵ **والسياسةُ في طبقة التطبيق حيث تُختبَر.**
/// ═══════════════════════════════════════════════════════════════════════
///
/// ⛔⛔★★★ **ولا تُعرَض القيمة المخزَّنة في أي واجهة ولا سجلٍّ ولا حقلٍ
/// مملوءٍ مسبقاً** — ★ **الشرط 3:** ⟵ **البصمةُ تفتح دخولاً** ⛔ **لا تكشف
/// سرّاً.**
library;

/// ★★ بياناتُ دخولٍ محفوظة — ⛔ **و`toString` لا تكشف كلمة المرور.**
final class StoredCredentials {
  /// ينشئ البيانات.
  const StoredCredentials({required this.email, required this.password});

  /// ★ البريد — ★ **يُعرَض في شاشة الدخول تلميحاً** ⛔ **لا في حقل.**
  final String email;

  /// ⛔⛔★★★ **كلمةُ المرور** — ★ **تُمرَّر لمسار الدخول القائم نفسِه**
  /// ⛔ **ولا تُقرأ لغير ذلك، ولا تُعرَض، ولا تُسجَّل.**
  final String password;

  /// ⛔⛔★★★ **ولا تكشف القيمة** — ★ **نفسُ حارس `InitialPassword` في النطاق:**
  /// ⟵ **رسائلُ الأخطاء وسجلاتُ التشخيص تستدعيها ضمناً** ⛔ **فتتسرّب بلا
  /// أن يقصد أحد.**
  @override
  String toString() => 'StoredCredentials($email, ***)';
}

/// ★ خزنةُ بيانات الدخول — ⛔ **مخزنٌ محضٌ بلا سياسة.**
abstract interface class CredentialVault {
  /// ★ يقرأ البيانات المحفوظة أو `null` — ⛔ **ولا يرمي على غيابها.**
  Future<StoredCredentials?> readIfPresent();

  /// ★ يحفظ البيانات — ⛔ **ويستبدل ما كان بلا سؤال.**
  Future<void> save(StoredCredentials credentials);

  /// ⛔⛔★★★ **يمسح المحفوظ فعلياً** — الشرط 6 في [`ADR-0024`]:
  /// ★ **ولا رايةٌ منطقية تُطفَأ والسرُّ باقٍ على القرص** ⟵ **فتُوهم بحذفٍ
  /// لم يقع.**
  Future<void> clear();

  /// ★ هل ثمّة بياناتٌ محفوظة؟ — ⛔ **ولا يقرؤها للإجابة.**
  ///
  /// ⚠️★★ **ولماذا سؤالٌ مستقل عن [readIfPresent]:** ★ **شاشةُ الدخول تحتاج
  /// أن تعرف هل تعرض زرَّ البصمة** — ⟵ **قبل أي مصادقة**، ⛔ **وقراءةُ
  /// الكلمة للإجابة تخالف الشرط 2** («لا تُقرأ إلا بعد نجاح المصادقة»).
  Future<bool> hasCredentials();
}
