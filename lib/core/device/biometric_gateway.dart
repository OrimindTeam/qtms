/// ★★★ **بوابةُ المصادقة البيومترية** — [`ADR-0024`] ⏳ **مقترح** · `AM-012` §5.2.
///
/// ═══════════════════════════════════════════════════════════════════════
/// ⛔⛔★★★ **واجهةٌ مجرَّدة لا استدعاءُ حزمةٍ مباشر — وهو شرطُ اختبارٍ لا ذوق:**
/// ★ **`local_auth` قناةُ منصّةٍ لا تعمل في اختبار ويدجت** — ⟵ **واستدعاؤها
/// من الشاشة كان يجعل كلَّ مسارات البصمة غيرَ قابلةٍ للاختبار الآلي إطلاقاً**،
/// ⛔ **فلا يبقى إلا القياسُ الحيّ على المحاكي** ★ **وهو لا يكفي بمفرده**
/// (`implementation-playbook.md` §7).
///
/// ★★ **وهو نفسُ نمط `ContactPicker` في هذا المشروع حرفياً** — ⛔ **ولا نمطَ
/// ثانٍ يُخترَع** (`ADR-0010` القاعدة 4: **حقن اعتمادية صريح**).
/// ═══════════════════════════════════════════════════════════════════════
library;

/// ★★ **حالةُ دعم البصمة على هذا الجهاز** — ⛔ **ثلاثيةٌ لا `bool`.**
///
/// ⛔⛔★★★ **ولماذا ثلاثةٌ لا اثنان — والفرق يصل المستخدم نصّاً:**
/// ★ **«الجهاز لا يدعم» و«يدعم ولا بصمةَ مسجَّلة» حالتان مختلفتان تماماً:**
/// ⟵ **الأولى لا حلَّ لها**، ★ **والثانية يحلّها المستخدم في إعدادات جهازه
/// خلال دقيقة** — ⛔ **ورسالةٌ واحدة لهما تترك نصفَ المستخدمين يظنّون
/// أجهزتهم عاجزة.**
enum BiometricAvailability {
  /// ✅ **متاحةٌ الآن** — ★ **الجهاز يدعمها وثمّة بصمةٌ مسجَّلة.**
  available,

  /// ⚠️ **الجهاز يدعمها ⛔ ولا بصمةَ مسجَّلة عليه** — ★ **يُوجَّه المستخدم.**
  notEnrolled,

  /// ⛔ **الجهاز لا يدعمها إطلاقاً** — ★ **ولا حلَّ في التطبيق.**
  unsupported,
}

/// ★ بوابةُ المصادقة البيومترية — ⛔ **بلا أي منطق أعمال.**
abstract interface class BiometricGateway {
  /// ★ يقرأ حالةَ الدعم — ⛔ **ولا يفترضها.**
  Future<BiometricAvailability> availability();

  /// ★★ يطلب مصادقةً بيومترية ويعيد نجاحَها.
  ///
  /// ⛔⛔★★★ **و`false` تعني «لم تنجح» لا «فشل النظام»** — ★ **والإلغاءُ من
  /// المستخدم يقع فيها**: ⟵ **فالمُستدعي لا يفتح شيئاً**، ⛔ **ولا يعرض
  /// خطأً على فعلٍ اختاره المستخدم بنفسه.**
  Future<bool> authenticate({required String reason});
}
