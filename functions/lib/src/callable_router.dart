/// `CallableClient` يبني `POST <base>/<اسم العملية>`، **بينما
/// `FUNCTION_TARGET` هدفٌ واحد لكل حاوية ولا يوجّه بالمسار**. ⟵ ⛔ **فحاويةٌ
/// بهدفٍ واحد كانت ستردّ على `/deleteRole` باستجابة `grantPermissions`**
/// — ★ **استجابةَ عمليةٍ غير المطلوبة بلا خطأ ظاهر**، وهو أسوأ من الفشل
