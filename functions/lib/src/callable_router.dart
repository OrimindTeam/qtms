///
/// ═══════════════════════════════════════════════════════════════════════
/// ⛔★★ **القواعد الأربع المُلزِمة من نصّ القرار — ⛔ ولا تُخفَّف:**
///
///   ① **كل مسار معروف يرتبط بمعالج واحد محدد** — ⛔ **ولا توجيه ضمني.**
///   ② **أي مسار غير معروف يُرفَض صراحةً** — ⛔ **ولا `fallback` إلى معالج
///      افتراضي**، ★ **ولا إلى أول عملية في القائمة.**
///   ③ **`FUNCTION_TARGET` يبقى هدف الحاوية الواحدة** — والاختيار بالمسار.
///   ④ **كل معالج يحتفظ بفحص مصادقته وتفويضه وتدقيقه** — ⛔ **والموجّه
///      لا يفحص شيئاً منها ولا ينوب عنها** (`ADR-0013` القاعدة 3).
/// ═══════════════════════════════════════════════════════════════════════
