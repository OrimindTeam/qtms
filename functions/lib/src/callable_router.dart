/// ★ يستخرج العملية من مسار الطلب — و`null` تعني **مساراً غير معروف**.
///
/// ★★ **دالة خالصة عمداً** — ⟵ **فالتوجيه يُختبَر بلا سحابة ولا شبكة**،
/// وهو حارسٌ حقيقي لا تفصيل نقل: **خطأٌ فيه يُسلّم الطلب لمعالجٍ آخر.**
///
/// **ما تتسامح معه صراحةً:** الشرطة البادئة والزائدة (`/createUser` ·
/// `createUser` · `/createUser/`) — ★ **فبوابات الوسط تُطبّع المسارات
/// اختلافاً بينها**، ⛔ **والتشدّد هنا يكسر الاستدعاء بلا سبب أمني.**
///
/// ⛔★★ **وما لا تتسامح معه إطلاقاً:**
///   · **اختلاف حالة الأحرف** (`/createuser`) — ⟵ **مساران مختلفان**،
///     ★ **والتطبيع كان سيُخفي خطأً برمجياً في العميل.**
///   · **مسارٌ مركّب** (`/v1/createUser`) — ⛔ **ولا يُقتطَع آخرُ مقطع**:
///     الاقتطاع يجعل `/anything/deleteRole` يُنفِّذ حذفاً، ⟵ **وهو توجيهٌ
///     ضمني تمنعه القاعدة ①.**
///   · **المسار الجذر** (`/`) — ⛔ **ولا يُعامَل عمليةً افتراضية.**
CallableOperation? resolveCallableOperation(String path) {
  // ⛔ **الشرطة البادئة والزائدة وحدهما تُقصّان** — ★ ولا شيء غيرهما.
  final String trimmed = path.replaceAll(RegExp(r'^/+|/+$'), '');
  if (trimmed.isEmpty) return null;
  for (final CallableOperation operation in CallableOperation.values) {
    // ★ **مطابقة تامة حسّاسة لحالة الأحرف** — راجع الترويسة.
    if (operation.name == trimmed) return operation;
  }
  return null;
}
